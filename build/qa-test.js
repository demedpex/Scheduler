function block(head){
  const i = HTML.indexOf(head);
  if(i < 0) throw new Error('없음: ' + head);
  let d = 0;
  for(let k = HTML.indexOf('{', i); k < HTML.length; k++){
    if(HTML[k] === '{') d++;
    else if(HTML[k] === '}'){ d--; if(!d) return HTML.slice(i, k + 1); }
  }
}
